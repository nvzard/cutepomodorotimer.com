export function t(lang: LangCode, key: ClientTranslationKey | string): string {
	const dict = clientTranslations[lang] as Record<string, string> | undefined;
	return dict?.[key] ?? (clientTranslations.en as Record<string, string>)[key] ?? key;
}

export function applyTranslations(lang: LangCode) {
	document.documentElement.lang = lang;
	document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
		const key = el.dataset.i18n;
		if (key) {
			const val = t(lang, key);
			if (val !== key) el.textContent = val;
		}
	});
	document.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
		const key = el.dataset.i18nAria;
		if (key) {
			const val = t(lang, key);
			if (val !== key) el.setAttribute('aria-label', val);
		}
	});
}
